import React, { useState } from 'react';
import { useAuth } from '../context/AuthContext';
import { useNavigate } from 'react-router-dom';
import { Button } from '../components/ui/Button';
import { Lock, Mail, KeyRound, ShieldCheck, Shield } from 'lucide-react';

export const LoginPage: React.FC = () => {
  const { login } = useAuth();
  const navigate = useNavigate();

  const [email, setEmail] = useState('');
  const [password, setPassword] = useState('');
  const [mfaCode, setMfaCode] = useState('');
  const [mfaRequired, setMfaRequired] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [loading, setLoading] = useState(false);

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    setError(null);
    setLoading(true);

    try {
      const result = await login(email, password, mfaRequired ? mfaCode : undefined);
      if (result.mfaRequired) {
        setMfaRequired(true);
      } else if (result.success) {
        navigate('/');
      } else {
        setError(result.error || 'Authentication failed. Please check credentials.');
      }
    } catch {
      setError('Unexpected network or server error during sign in.');
    } finally {
      setLoading(false);
    }
  };

  return (
    <div className="min-h-screen flex items-center justify-center p-4 sm:p-6 lg:p-8">
      <div className="w-full max-w-md mx-auto space-y-6">
        {/* Brand Banner */}
        <div className="text-center">
          <div className="inline-flex items-center justify-center w-16 h-16 rounded-2xl bg-gradient-to-br from-[#3FD2C0] to-[#17A58F] text-[#062F2E] font-black text-2xl mb-3 shadow-[0_0_32px_rgba(63,210,192,0.45)] border border-[rgba(255,255,255,0.3)]">
            NR
          </div>
          <h1 className="text-2xl sm:text-3xl font-extrabold text-[#EAF6F4] tracking-tight">
            NovaRetail Support Desk
          </h1>
          <p className="text-xs uppercase font-bold tracking-widest text-[#3FD2C0] mt-1.5 flex items-center justify-center gap-1.5">
            <Shield className="w-3.5 h-3.5" />
            <span>Master Control Console • Spec 15.1.8</span>
          </p>
        </div>

        {/* Login Glass Card with Reference Notched Top Edge */}
        <div className="glass-panel p-6 sm:p-8 rounded-3xl relative border border-[rgba(63,210,192,0.35)] shadow-[0_24px_64px_rgba(0,0,0,0.65)] backdrop-blur-xl">
          {/* Reference Signature: Notched Tab Pill on panel edge */}
          <div className="notched-tab-pill">
            <span className="text-[10px] uppercase font-bold tracking-widest text-[#3FD2C0]">
              STAFF AUTHENTICATION
            </span>
          </div>

          <div className="mb-6 pt-2">
            <h2 className="text-xl font-bold text-[#EAF6F4]">
              {mfaRequired ? 'Multi-Factor Verification' : 'Staff Sign In'}
            </h2>
            <p className="text-xs text-[#B6D5D1] mt-1.5 leading-relaxed">
              {mfaRequired
                ? 'Enter the 6-digit TOTP code generated by your authenticator app.'
                : 'Customer tokens are never valid here. Authenticate using authorized staff credentials.'}
            </p>
          </div>

          {error && (
            <div className="mb-5 p-3.5 rounded-xl bg-[rgba(255,82,82,0.15)] border border-[rgba(255,82,82,0.4)] text-[#FF8585] text-xs leading-relaxed flex items-start gap-2">
              <span className="shrink-0 font-bold">⚠️</span>
              <span>{error}</span>
            </div>
          )}

          <form onSubmit={handleSubmit} className="space-y-4">
            {!mfaRequired ? (
              <>
                <div>
                  <label className="block text-[11px] font-bold uppercase tracking-wider text-[#3FD2C0] mb-1.5">
                    Staff Email Address
                  </label>
                  <div className="relative">
                    <Mail className="absolute left-3.5 top-3.5 w-4 h-4 text-[#84ABA6]" />
                    <input
                      type="email"
                      required
                      value={email}
                      onChange={(e) => setEmail(e.target.value)}
                      placeholder="e.g. executive@novaretail.com"
                      className="w-full pl-10 pr-4 py-3 rounded-xl bg-[rgba(6,47,46,0.85)] border border-[rgba(63,210,192,0.25)] text-[#EAF6F4] placeholder-[#84ABA6] focus:border-[#3FD2C0] focus:ring-2 focus:ring-[rgba(63,210,192,0.3)] outline-none text-sm transition-all"
                    />
                  </div>
                </div>

                <div>
                  <label className="block text-[11px] font-bold uppercase tracking-wider text-[#3FD2C0] mb-1.5">
                    Password
                  </label>
                  <div className="relative">
                    <Lock className="absolute left-3.5 top-3.5 w-4 h-4 text-[#84ABA6]" />
                    <input
                      type="password"
                      required
                      value={password}
                      onChange={(e) => setPassword(e.target.value)}
                      placeholder="••••••••••••"
                      className="w-full pl-10 pr-4 py-3 rounded-xl bg-[rgba(6,47,46,0.85)] border border-[rgba(63,210,192,0.25)] text-[#EAF6F4] placeholder-[#84ABA6] focus:border-[#3FD2C0] focus:ring-2 focus:ring-[rgba(63,210,192,0.3)] outline-none text-sm transition-all"
                    />
                  </div>
                </div>
              </>
            ) : (
              <div>
                <label className="block text-[11px] font-bold uppercase tracking-wider text-[#3FD2C0] mb-1.5">
                  6-Digit MFA / TOTP Code
                </label>
                <div className="relative">
                  <KeyRound className="absolute left-3.5 top-3.5 w-4 h-4 text-[#3FD2C0]" />
                  <input
                    autoFocus
                    type="text"
                    maxLength={6}
                    required
                    value={mfaCode}
                    onChange={(e) => setMfaCode(e.target.value)}
                    placeholder="123456"
                    className="w-full pl-10 pr-4 py-3 rounded-xl bg-[rgba(6,47,46,0.9)] border border-[#3FD2C0] text-[#EAF6F4] placeholder-[#84ABA6] focus:border-[#3FD2C0] focus:ring-2 focus:ring-[rgba(63,210,192,0.3)] outline-none text-base font-mono tracking-widest text-center"
                  />
                </div>
              </div>
            )}

            <Button
              type="submit"
              variant="primary"
              size="lg"
              isLoading={loading}
              className="w-full mt-2 font-bold tracking-wide"
              leftIcon={<ShieldCheck className="w-5 h-5" />}
            >
              {mfaRequired ? 'Verify & Enter Console' : 'Continue with MFA / Sign In'}
            </Button>
          </form>
        </div>
      </div>
    </div>
  );
};
