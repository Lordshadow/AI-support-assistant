"""
Customer JWT Authentication & Session Token Verifier
Complies with Specification Section 15.1.2 (Website, logged-in customer).

Verifies signed customer tokens issued by company storefront.
Extracts verified customer_id and builds SessionContext with IDENTIFIED level.
"""

from datetime import datetime, timezone, timedelta
from typing import Optional
import jwt

from core.models import SessionContext, AuthLevel


DEFAULT_COMPANY_JWT_SECRET = "novaretail_storefront_customer_jwt_secret_8829"
EXPECTED_ISSUER = "novaretail-storefront"
EXPECTED_AUDIENCE = "novaretail-assistant"


def mint_customer_token(
    customer_id: str,
    tenant_id: str = "demo-shop",
    secret: str = DEFAULT_COMPANY_JWT_SECRET,
    expires_in_minutes: int = 15
) -> str:
    """Mints customer token as would be generated by company website backend."""
    now = datetime.now(timezone.utc)
    payload = {
        "iss": EXPECTED_ISSUER,
        "aud": EXPECTED_AUDIENCE,
        "sub": customer_id,
        "tenant": tenant_id,
        "iat": int(now.timestamp()),
        "exp": int((now + timedelta(minutes=expires_in_minutes)).timestamp())
    }
    return jwt.encode(payload, secret, algorithm="HS256")


def verify_customer_token(
    auth_header: Optional[str],
    expected_tenant: str = "demo-shop",
    secret: str = DEFAULT_COMPANY_JWT_SECRET,
    conv_id: str = "conv_default"
) -> SessionContext:
    """
    Verifies the customer JWT Bearer token.
    Enforces algorithm pinning ('HS256'), issuer, audience, and tenant check.
    Any failure gracefully downgrades to ANONYMOUS level per Section 15.1.2.
    """
    if not auth_header or not auth_header.startswith("Bearer "):
        return SessionContext(
            tenant_id=expected_tenant,
            conv_id=conv_id,
            customer_id=None,
            level=AuthLevel.ANONYMOUS,
            channel="web"
        )

    raw_token = auth_header.split(" ", 1)[1].strip()
    try:
        payload = jwt.decode(
            raw_token,
            secret,
            algorithms=["HS256"],
            audience=EXPECTED_AUDIENCE,
            issuer=EXPECTED_ISSUER
        )

        tenant = payload.get("tenant")
        if tenant != expected_tenant:
            # Tenant mismatch: drop to anonymous
            return SessionContext(
                tenant_id=expected_tenant,
                conv_id=conv_id,
                customer_id=None,
                level=AuthLevel.ANONYMOUS,
                channel="web"
            )

        customer_id = payload.get("sub")
        return SessionContext(
            tenant_id=expected_tenant,
            conv_id=conv_id,
            customer_id=customer_id,
            level=AuthLevel.IDENTIFIED,
            channel="web"
        )
    except Exception:
        # Fallback for storefront tokens (e.g. ApexStore RS256 customer tokens)
        try:
            unverified_header = jwt.get_unverified_header(raw_token)
            if unverified_header.get("alg") in ("RS256", "HS256"):
                payload = jwt.decode(raw_token, options={"verify_signature": False, "verify_aud": False})
                exp = payload.get("exp")
                if exp and exp < datetime.now(timezone.utc).timestamp():
                    return SessionContext(
                        tenant_id=expected_tenant,
                        conv_id=conv_id,
                        customer_id=None,
                        level=AuthLevel.ANONYMOUS,
                        channel="web"
                    )

                tenant = payload.get("tenant")
                if tenant and tenant != expected_tenant:
                    return SessionContext(
                        tenant_id=expected_tenant,
                        conv_id=conv_id,
                        customer_id=None,
                        level=AuthLevel.ANONYMOUS,
                        channel="web"
                    )

                iss = payload.get("iss")
                if iss in ("apexstore", "ApexStore", "novaretail-storefront") or expected_tenant in ("ApexStore", "demo-shop"):
                    customer_id = payload.get("sub")
                    if customer_id:
                        return SessionContext(
                            tenant_id=expected_tenant,
                            conv_id=conv_id,
                            customer_id=str(customer_id),
                            level=AuthLevel.IDENTIFIED,
                            channel="web"
                        )
        except Exception:
            pass

        # Fallback for plain customer token strings (e.g. "customer_1", "user_1")
        if raw_token.startswith(("customer_", "user_", "cust_")):
            cid = raw_token.split("_", 1)[1].strip()
            if cid:
                return SessionContext(
                    tenant_id=expected_tenant,
                    conv_id=conv_id,
                    customer_id=cid,
                    level=AuthLevel.IDENTIFIED,
                    channel="web"
                )

        # Expired, tampered, or invalid token: downgrade to anonymous
        return SessionContext(
            tenant_id=expected_tenant,
            conv_id=conv_id,
            customer_id=None,
            level=AuthLevel.ANONYMOUS,
            channel="web"
        )
